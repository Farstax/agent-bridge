/**
 * Source-only setup helpers for standalone Discord/Slack companions (#1003).
 * No production service, release pointer or existing DB is modified here.
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { constants, existsSync, mkdirSync, openSync, closeSync, readFileSync, writeFileSync, chmodSync, renameSync, unlinkSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { WebClient } from "@slack/web-api";
import { assertSupportedSlackTokens, verifySlackBotIdentity } from "./slackIdentity.js";
import type { DetectedInteractiveProvider } from "./setup.js";

export type SetupSurface = "telegram" | "discord" | "slack";
export function parseSetupSurface(raw: string): SetupSurface {
  if (raw === "telegram" || raw === "discord" || raw === "slack") return raw;
  throw new Error("Surface must be telegram, discord or slack.");
}

export function normalizeSetupUserIds(raw: string, surface: "discord" | "slack"): string {
  const ids = [...new Set(raw.split(",").map(x => x.trim()).filter(Boolean))];
  if (!ids.length || ids.some(x => !(surface === "discord" ? /^\d{15,22}$/.test(x) : /^[UW][A-Z0-9]{2,}$/.test(x)))) {
    throw new Error("Invalid " + surface + " allowed user IDs (default deny).");
  }
  return ids.join(",");
}
function q(value: string): string { return JSON.stringify(value); }
export function surfaceSourceDbPath(projectDir: string, surface: "discord" | "slack"): string {
  return join(resolve(projectDir), ".data", surface + "-interactive.sqlite");
}
export function renderSurfaceSetupEnv(input: {
  surface: "discord" | "slack"; projectDir: string; userIds: string;
  providers: readonly DetectedInteractiveProvider[];
  discordBotToken?: string; discordApplicationId?: string; discordGuildId?: string;
  slackBotTokenFile?: string; slackAppTokenFile?: string;
}): string {
  if (!input.providers.length) throw new Error("At least one provider CLI is required.");
  const projectDir = resolve(input.projectDir);
  const userIds = normalizeSetupUserIds(input.userIds, input.surface);
  const chain = input.providers.map(p => p.chainKind).join(",");
  const commands = input.providers.map(p => p.commandEnv + "=" + q(p.commandPath));
  let credentials: string[];
  if (input.surface === "discord") {
    if (!input.discordBotToken?.trim() || !/^\d{15,22}$/.test(input.discordApplicationId || "")) {
      throw new Error("Discord bot token and numeric application ID are required.");
    }
    credentials = [
      "DISCORD_BOT_TOKEN=" + q(input.discordBotToken.trim()),
      "DISCORD_APPLICATION_ID=" + q(input.discordApplicationId!),
      "DISCORD_ALLOWED_USER_IDS=" + q(userIds),
      ...(input.discordGuildId?.trim() ? ["DISCORD_GUILD_ID=" + q(input.discordGuildId.trim())] : []),
    ];
  } else {
    if (!input.slackBotTokenFile || !input.slackAppTokenFile) throw new Error("Both Slack credential files are required.");
    credentials = [
      "SLACK_BOT_TOKEN_FILE=" + q(resolve(input.slackBotTokenFile)),
      "SLACK_APP_TOKEN_FILE=" + q(resolve(input.slackAppTokenFile)),
      "SLACK_ALLOWED_USER_IDS=" + q(userIds),
      "BRIDGE_EXECUTION_MODE=safe",
    ];
  }
  return [
    "# Generated by Agent Bridge standalone source setup (#1003).",
    ...credentials,
    "BRIDGE_PROJECT_DIR=" + q(projectDir),
    "DB_PATH=" + q(surfaceSourceDbPath(projectDir, input.surface)),
    ...commands,
    "INTERACTIVE_CLI_CHAIN=" + q(chain),
    "INTERACTIVE_DEFAULT_CLI=" + input.providers[0].chainKind,
    "BRIDGE_BUSY_MESSAGE_MODE=augment",
    "",
  ].join("\n");
}
/** Bot token verification; app ID must match the token's real application. */
export async function verifyDiscordBot(token: string, applicationId: string, fetcher: typeof fetch = fetch): Promise<void> {
  if (!token.trim()) throw new Error("Discord bot token is required.");
  const headers = { Authorization: "Bot " + token.trim() };
  for (const [path, isApp] of [["users/@me", false], ["oauth2/applications/@me", true]] as const) {
    let response: Response;
    try { response = await fetcher("https://discord.com/api/v10/" + path, { headers, signal: AbortSignal.timeout(10000) }); }
    catch { throw new Error("Discord credential verification could not reach Discord."); }
    if (!response.ok) throw new Error("Discord credential verification failed (HTTP " + response.status + "). Check the bot token and permissions.");
    const data: any = await response.json();
    if (isApp && String(data?.id ?? "") !== applicationId) throw new Error("Discord application ID does not match the bot token.");
    if (!isApp && !data?.bot) throw new Error("Discord token does not belong to a bot user.");
  }
}
/** Bot token preflight only: actual xapp-to-app binding happens on the runtime Socket Mode hello. */
export async function verifySlackSetup(botToken: string, appToken: string, userIds: string[]): Promise<string> {
  assertSupportedSlackTokens(botToken, appToken);
  const web = new WebClient(botToken, { retryConfig: { retries: 0 }, timeout: 10000 });
  const identity = await verifySlackBotIdentity(web);
  for (const id of userIds) {
    const response: any = await web.users.info({ user: id });
    const user = response?.user;
    if (!user || user.deleted || user.is_bot || (user.team_id && user.team_id !== identity.teamId)) {
      throw new Error("A Slack allowlisted ID is inactive, a bot or outside the verified workspace.");
    }
  }
  return identity.appId;
}
export function sourceSlackCredentialPaths(checkout: string): { bot: string; app: string } {
  const key = createHash("sha256").update(resolve(checkout)).digest("hex").slice(0, 20);
  const dir = join(homedir(), ".config", "agent-bridge", "slack-" + key);
  return { bot: join(dir, "bot-token"), app: join(dir, "app-token") };
}
export function writePrivateSlackTokenFiles(paths: { bot: string; app: string }, botToken: string, appToken: string): void {
  assertSupportedSlackTokens(botToken, appToken);
  if (existsSync(paths.bot) || existsSync(paths.app)) {
    // Setup must not rewrite a live bot's credential during a config-only --force.
    throw new Error("Slack token files already exist. Preserve them and configure using their existing paths; rotate manually with the runtime stopped.");
  }
  if (dirname(paths.bot) !== dirname(paths.app)) throw new Error("Slack tokens must have one private directory.");
  mkdirSync(dirname(paths.bot), { recursive: true, mode: 0o700 });
  chmodSync(dirname(paths.bot), 0o700);
  try {
    for (const [path, token] of [[paths.bot, botToken], [paths.app, appToken]]) {
      const fd = openSync(path, constants.O_CREAT | constants.O_EXCL | constants.O_WRONLY | constants.O_NOFOLLOW, 0o600);
      try { writeFileSync(fd, token.trim() + "\n"); } finally { closeSync(fd); }
    }
  } catch (error) {
    for (const path of [paths.bot, paths.app]) { if (existsSync(path)) unlinkSync(path); }
    throw error;
  }
}
/** Uses the already-shipped guarded role bootstrap. A pre-existing DB is never touched. */
export function bootstrapSourceSurfaceDb(dbPath: string, role: "discord" | "slack"): void {
  if (existsSync(dbPath)) return; // Existing history is immutable to setup; runtime validates its schema.
  mkdirSync(dirname(dbPath), { recursive: true });
  try {
    execFileSync(process.execPath, ["--import", "tsx", "scripts/rollout-db.ts", "bootstrap", "--db", dbPath, "--role", role, "--confirm-new-role", dbPath], {
      cwd: resolve("."), stdio: ["ignore", "pipe", "pipe"], timeout: 120000,
    });
  } catch {
    throw new Error("Guarded " + role + " database bootstrap failed. See docs/INITIAL-INSTALL.md; setup did not change an existing DB.");
  }
}
